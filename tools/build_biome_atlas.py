def _load(name: str):
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def _name_map(rows: list[dict]) -> dict[str, str]:
    return {str(row["id"]): str(row["name"]) for row in rows}


def _visual_path(visuals: dict, kind: str, content_id: str, *, last: bool = False) -> Path | None:
    raw = visuals.get(kind, {}).get(content_id)
    if isinstance(raw, list):
        if not raw:
            return None
        raw = raw[-1] if last else raw[0]
    if not isinstance(raw, str):
        return None
    path = WORLDSEED / raw
    return path if path.is_file() else None


def _resource_kind(row: dict) -> str:
    tags = set(row.get("tags", []))
    if "natural_container" in tags:
        return "container"
    if "tree" in tags:
        return "tree"
    if "living" in tags:
        return "plant"
    if tags & {"rock", "stone", "clay", "soil"}:
        return "deposit"
    return "resource"


def _resource_seasons(row: dict) -> str:
    seasons = list(row.get("seasons") or [])
    return ", ".join(seasons) if seasons else "year-round"


def _yield_summary(row: dict, item_names: dict[str, str]) -> str:
    parts = []
    for item_id, amount in sorted((row.get("yields") or {}).items()):
        lo, hi = int(amount[0]), int(amount[1])
        qty = str(lo) if lo == hi else f"{lo}-{hi}"
        parts.append(f"{item_names.get(item_id, item_id)} x{qty}")
    return ", ".join(parts) if parts else "—"


def _terrain_feature_summary(row: dict, item_names: dict[str, str]) -> str:
    gather = row.get("gather_item")
    if gather:
        return f"Gather: {item_names.get(gather, gather)} x{int(row.get('gather_amount', 0))}"
    tags = set(row.get("tags") or [])
    markers = []
    for tag in ("river", "rapids", "freshwater", "saltwater", "brackish", "shore", "cliff", "tidal", "wetland", "shaft", "ruin", "farm"):
        if tag in tags:
            markers.append(tag.replace("_", " "))
    return ", ".join(markers) if markers else "terrain"


def build_catalog() -> dict:
    terrains = _load("terrain.json")
    resources = _load("resources.json")
    species = _load("species.json")
    crops = _load("crops.json")
    items = _load("items.json")
    terrain_by_id = {row["id"]: row for row in terrains}
    item_names = _name_map(items)

    groups: list[dict] = []
    resource_memberships: Counter[str] = Counter()
    species_memberships: Counter[str] = Counter()

    interim = []
    for definition in BIOME_GROUPS:
        terrain_ids = tuple(definition["terrains"])
        habitat_ids = set(definition.get("habitats", ()))
        eligible_resources = []
        for row in resources:
            declared = tuple(row.get("terrains") or ())
            if any(tid in terrain_ids for tid in declared):
                eligible_resources.append(row)
                resource_memberships[row["id"]] += 1
        eligible_species = []
        for row in species:
            if habitat_ids.intersection(row.get("habitats") or ()):
                eligible_species.append(row)
                species_memberships[row["id"]] += 1
        interim.append((definition, eligible_resources, eligible_species))

    for definition, eligible_resources, eligible_species in interim:
        grouped_resources = {"tree": [], "plant": [], "deposit": [], "resource": [], "container": []}
        for row in eligible_resources:
            grouped_resources[_resource_kind(row)].append({
                "id": row["id"],
                "name": row["name"],
                "seasons": list(row.get("seasons") or []),
                "season_label": _resource_seasons(row),
                "density": int(row.get("density", 0)),
                "yields": _yield_summary(row, item_names),
                "exclusive": resource_memberships[row["id"]] == 1,
            })
        for rows in grouped_resources.values():
            rows.sort(key=lambda x: (x["name"].casefold(), x["id"]))

        animals = []
        for row in eligible_species:
            animals.append({
                "id": row["id"],
                "name": row["name"],
                "diet": row["diet"],
                "group": [int(row.get("group_min", 1)), int(row.get("group_max", 1))],
                "exclusive": species_memberships[row["id"]] == 1,
                "climate_limited": (
                    int(row.get("min_temp", 0)) > 0
                    or int(row.get("max_temp", 65535)) < 65535
                    or int(row.get("min_moisture", 0)) > 0
                    or int(row.get("max_moisture", 65535)) < 65535
                ),
            })
        animals.sort(key=lambda x: (x["name"].casefold(), x["id"]))

        terrain_features = []
        for tid in definition["terrains"]:
            row = terrain_by_id[tid]
            terrain_features.append({
                "id": tid,
                "name": row["name"],
                "tags": list(row.get("tags") or []),
                "feature": _terrain_feature_summary(row, item_names),
            })

        crop_rows = []
        if definition["id"] == "farmland":
            for row in crops:
                crop_rows.append({
                    "id": row["id"],
                    "name": row["name"],
                    "seasons": list(row.get("seasons") or []),
                    "season_label": ", ".join(row.get("seasons") or []),
                })
            crop_rows.sort(key=lambda x: (x["name"].casefold(), x["id"]))

        gaps = []
        if definition["kind"] in {"freshwater", "coast", "marine"} and not eligible_species:
            gaps.append("No authored animal habitat currently targets these terrain IDs.")
        if definition["kind"] in {"freshwater", "coast", "marine"} and not eligible_resources:
            gaps.append("No authored ResourceSystem spawn currently targets these terrain IDs.")
        if definition["id"] in {"wetland", "floodplain"} and not eligible_species:
            gaps.append("No species habitat currently targets wetland/floodplain terrain directly.")
        if definition["id"] == "ancient_ruins":
            gaps.append("Ruin terrain features are generated as underground site terrain rather than ResourceSystem spawns.")
        if definition["id"] == "farmland":
            gaps.append("Crops are planted simulation state, not natural resource spawns.")

        groups.append({
            "id": definition["id"],
            "name": definition["name"],
            "kind": definition["kind"],
            "description": definition["description"],
            "terrain": terrain_features,
            "trees": grouped_resources["tree"],
            "plants": grouped_resources["plant"],
            "deposits": grouped_resources["deposit"] + grouped_resources["resource"],
            "containers": grouped_resources["container"],
            "animals": animals,
            "crops": crop_rows,
            "gaps": gaps,
        })

    return {
        "version": 1,
        "source": {
            "terrain": "data/terrain.json",
            "resources": "data/resources.json",
            "species": "data/species.json",
            "crops": "data/crops.json",
            "visuals": "assets/visuals.json",
        },
        "note": "Entries are spawn eligibility, not guaranteed presence. Climate, season, density, deterministic placement, and simulation state still apply.",
        "biomes": groups,
    }


def _font(size: int, bold: bool = False):
    names = ("DejaVuSans-Bold.ttf", "DejaVuSans.ttf") if bold else ("DejaVuSans.ttf",)
    for name in names:
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            pass
    return ImageFont.load_default()


def _ellipsize(text: str, limit: int) -> str:
    return text if len(text) <= limit else text[: max(1, limit - 1)] + "…"


def _icon_for(visuals: dict, kind: str, content_id: str, *, last: bool = False) -> Image.Image | None:
    path = _visual_path(visuals, kind, content_id, last=last)
    if path is None:
        return None
    try:
        return Image.open(path).convert("RGBA")
    except Exception:
        return None


def _chip(canvas: Image.Image, draw: ImageDraw.ImageDraw, x: int, y: int, w: int, item: dict, icon: Image.Image | None, suffix: str = "") -> None:
    draw.rounded_rectangle((x, y, x + w, y + 58), radius=6, fill=(26, 30, 32, 255), outline=(63, 72, 75, 255))
    if icon is not None:
        icon = icon.copy()
        icon.thumbnail((44, 44), Image.Resampling.LANCZOS)
        canvas.alpha_composite(icon, (x + 8 + (44 - icon.width) // 2, y + 7 + (44 - icon.height) // 2))
    name = str(item["name"]) + (" ★" if item.get("exclusive") else "")
    draw.text((x + 60, y + 10), _ellipsize(name, 27), fill=(230, 232, 226, 255), font=_font(13, True))
    meta = suffix or str(item.get("feature") or item.get("season_label") or item.get("diet") or item.get("id", ""))
    draw.text((x + 60, y + 31), _ellipsize(meta, 32), fill=(152, 162, 159, 255), font=_font(10))


def _section_height(count: int, cols: int = 4) -> int:
    return 0 if count <= 0 else 26 + math.ceil(count / cols) * 64


def _draw_section(canvas: Image.Image, draw: ImageDraw.ImageDraw, visuals: dict, y: int, title: str, rows: list[dict], visual_kind: str, *, crop: bool = False) -> int:
    if not rows:
        return y
    draw.text((34, y), title, fill=(207, 172, 99, 255), font=_font(15, True))
    y += 24
    cols = 4
    chip_w = 270
    for i, row in enumerate(rows):
        col, line = i % cols, i // cols
        x = 34 + col * (chip_w + 10)
        cy = y + line * 64
        icon = _icon_for(visuals, visual_kind, row["id"], last=crop)
        suffix = ""
        if title == "Animals":
            lo, hi = row.get("group", [1, 1])
            suffix = f"{row.get('diet', '')} • group {lo}-{hi}"
        elif title in {"Plants & Forage", "Trees", "Crops"}:
            suffix = row.get("season_label", "")
        elif title == "Natural Containers":
            suffix = "natural container"
        _chip(canvas, draw, x, cy, chip_w, row, icon, suffix)
    return y + math.ceil(len(rows) / cols) * 64 + 6


def build_png(catalog: dict, visuals: dict) -> None:
    card_heights = []
    for biome in catalog["biomes"]:
        h = 126
        h += _section_height(len(biome["terrain"]))
        h += _section_height(len(biome["trees"]))
        h += _section_height(len(biome["plants"]))
        h += _section_height(len(biome["animals"]))
        h += _section_height(len(biome["containers"]))
        h += _section_height(len(biome["deposits"]))
        h += _section_height(len(biome["crops"]))
        if biome["gaps"]:
            h += 30 + 18 * len(biome["gaps"])
        card_heights.append(h)

    width = 1160
    margin = 22
    total_h = 92 + sum(card_heights) + margin * (len(card_heights) + 1)
    canvas = Image.new("RGBA", (width, total_h), (13, 16, 18, 255))
    draw = ImageDraw.Draw(canvas)
    draw.text((margin, 18), "WORLDSEED Biome Atlas", fill=(237, 233, 220, 255), font=_font(27, True))
    draw.text((margin, 54), "Terrain • plants • animals • natural containers • deposits • crops", fill=(154, 164, 160, 255), font=_font(12))
    draw.text((835, 54), "★ exclusive to one atlas biome group", fill=(181, 155, 103, 255), font=_font(10))

    y = 92
    card_regions = []
    for biome, card_h in zip(catalog["biomes"], card_heights):
        card_top = y
        draw.rounded_rectangle((margin, y, width - margin, y + card_h), radius=10, fill=(20, 24, 26, 255), outline=(66, 76, 79, 255))
        draw.text((34, y + 14), biome["name"], fill=(235, 231, 219, 255), font=_font(21, True))
        draw.text((34, y + 43), biome["kind"].upper(), fill=(197, 158, 83, 255), font=_font(10, True))
        draw.text((112, y + 42), _ellipsize(biome["description"], 150), fill=(158, 167, 164, 255), font=_font(11))
        cy = y + 70
        cy = _draw_section(canvas, draw, visuals, cy, "Terrain & Physical Features", biome["terrain"], "terrain")
        cy = _draw_section(canvas, draw, visuals, cy, "Trees", biome["trees"], "resources")
        cy = _draw_section(canvas, draw, visuals, cy, "Plants & Forage", biome["plants"], "resources")
        cy = _draw_section(canvas, draw, visuals, cy, "Animals", biome["animals"], "species")
        cy = _draw_section(canvas, draw, visuals, cy, "Natural Containers", biome["containers"], "resources")
        cy = _draw_section(canvas, draw, visuals, cy, "Deposits & Loose Resources", biome["deposits"], "resources")
        cy = _draw_section(canvas, draw, visuals, cy, "Crops", biome["crops"], "crops", crop=True)
        if biome["gaps"]:
            draw.text((34, cy), "Coverage notes", fill=(207, 172, 99, 255), font=_font(14, True))
            cy += 22
            for gap in biome["gaps"]:
                draw.text((44, cy), "• " + _ellipsize(gap, 145), fill=(170, 178, 175, 255), font=_font(10))
                cy += 18
        card_regions.append((biome["id"], card_top, card_top + card_h))
        y += card_h + margin

    canvas.save(ASSETS / "biome_atlas.png", optimize=True)
    detail_dir = ASSETS / "biome_atlas"
    detail_dir.mkdir(parents=True, exist_ok=True)
    expected = set()
    for biome_id, top, bottom in card_regions:
        expected.add(f"{biome_id}.png")
        crop = canvas.crop((max(0, margin - 6), max(0, top - 6), min(width, width - margin + 6), min(total_h, bottom + 6)))
        crop.save(detail_dir / f"{biome_id}.png", optimize=True)
    for path in detail_dir.glob("*.png"):
        if path.name not in expected:
            path.unlink()


def markdown_catalog(catalog: dict) -> str:
    lines = [
        "# WORLDSEED Biome Atlas",
        "",
        "Generated from the current terrain, resource, species, crop, and visual catalogs. Entries describe eligible spawns, not guaranteed presence; climate, season, density, deterministic placement, and simulation state still apply.",
        "",
        "A ★ marks an entry that is eligible in only one atlas biome group. This atlas does not invent missing aquatic wildlife/resource definitions.",
        "",
        '<img src="biome_atlas.png" width="1100">',
        "",
    ]
    for biome in catalog["biomes"]:
        lines += [
            f"## {biome['name']}",
            "",
            biome["description"],
            "",
            f'<img src="biome_atlas/{biome["id"]}.png" width="1100">',
            "",
        ]
        lines += ["### Terrain and physical features", "", "| Terrain | Runtime ID | Feature |", "|---|---|---|"]
        for row in biome["terrain"]:
            lines.append(f"| {row['name']} | {row['id']} | {row['feature']} |")
        lines.append("")

        for key, title in (
            ("trees", "Trees"),
            ("plants", "Plants and forage"),
            ("animals", "Animals"),
            ("containers", "Natural containers"),
            ("deposits", "Deposits and loose resources"),
            ("crops", "Crops"),
        ):
            rows = biome[key]
            if not rows:
                continue
            lines += [f"### {title}", ""]
            if key in {"trees", "plants", "deposits", "containers"}:
                lines += ["| Feature | Seasons | Density | Yields |", "|---|---|---:|---|"]
                for row in rows:
                    star = " ★" if row.get("exclusive") else ""
                    lines.append(f"| {row['name']}{star} | {row.get('season_label', 'year-round')} | {row.get('density', 0)} | {row.get('yields', '—')} |")
            elif key == "animals":
                lines += ["| Animal | Diet | Group | Climate-limited |", "|---|---|---:|---|"]
                for row in rows:
                    star = " ★" if row.get("exclusive") else ""
                    lo, hi = row["group"]
                    lines.append(f"| {row['name']}{star} | {row['diet']} | {lo}-{hi} | {'yes' if row['climate_limited'] else 'no'} |")
            else:
                lines += ["| Crop | Seasons |", "|---|---|"]
                for row in rows:
                    lines.append(f"| {row['name']} | {row['season_label']} |")
            lines.append("")

        if biome["gaps"]:
            lines += ["### Coverage notes", ""]
            for gap in biome["gaps"]:
                lines.append(f"- {gap}")
            lines.append("")

    return "\n".join(lines) + "\n"


def write_outputs() -> dict:
    catalog = build_catalog()
    visuals = json.loads((ASSETS / "visuals.json").read_text(encoding="utf-8"))
    (ASSETS / "biome_catalog.json").write_text(json.dumps(catalog, indent=2) + "\n", encoding="utf-8")
    (ASSETS / "BIOME_ATLAS.md").write_text(markdown_catalog(catalog), encoding="utf-8")
    build_png(catalog, visuals)
    return catalog


def main() -> int:
    catalog = write_outputs()
    terrain_count = sum(len(x["terrain"]) for x in catalog["biomes"])
    print(f"built biome atlas: {len(catalog['biomes'])} groups, {terrain_count} terrain definitions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
