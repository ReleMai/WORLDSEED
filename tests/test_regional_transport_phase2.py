from __future__ import annotations

import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace

from worldseed.config import DATA_DIR
from worldseed.content.registry import ContentRegistry
from worldseed.persistence.database import WorldDatabase
from worldseed.systems.economy import EconomySystem
from worldseed.systems.history import HistorySystem
from worldseed.systems.physicalization import SettlementPhysicalizationSystem
from worldseed.systems.route_planner import RoutePlanner
from worldseed.systems.settlement_planner import SettlementSkeletonPlanner
from worldseed.systems.state import FactionState, LivingWorldState, SettlementState
from worldseed.world.generator import WorldGenerator
from worldseed.world.region_blocks import RegionBlockPlanner
from worldseed.world.world import World


class RegionalTransportPhase2Tests(unittest.TestCase):
    def make_world(self, seed=b"regional-transport-phase2"):
        td=tempfile.TemporaryDirectory();self.addCleanup(td.cleanup)
        reg=ContentRegistry.load(DATA_DIR)
        db=WorldDatabase.create(Path(td.name)/"world.db","transport",seed.hex());self.addCleanup(db.close)
        world=World(WorldGenerator(seed,reg),reg,db)
        # These are transport/physicalization unit tests, not hydrology
        # integration tests. Production settlement planning consumes prepared
        # environmental data; using an explicit legal read model here prevents
        # the suite from depending on whether a hydrology domain happened to be
        # pre-generated by another test.
        transport_env=SimpleNamespace(
            open_water=False,slope=8,relief=12,soil_fertility=72,wetness=42,
            drainage=68,flood_risk=6,farmland=70,
            resources=SimpleNamespace(forage=55,timber=60,stone=45,freshwater=50),
            resource_opportunity=55,
        )
        world.environment_at=lambda _pos: transport_env
        world.settlement_plan_version=5
        world.routegen_version=3
        return world,reg,db

    def make_state(self,world,count=5):
        regions=RegionBlockPlanner(world)
        state=LivingWorldState()
        state.factions["faction:test"]=FactionState("faction:test","Test Compact","culture:test",treasury=2000,prominence=70)
        rows=[]
        for y in range(-4,5):
            for x in range(-4,5):
                plan=regions.plan(x,y,persist=True)
                if not plan.settlement_present or plan.settlement_anchor is None:
                    continue
                uid=f"settlement:{x}:{y}"
                town=SettlementState(
                    uid,f"Town {len(rows)}",x,y,plan.settlement_anchor[0],plan.settlement_anchor[1],
                    70+len(rows)*20,"culture:test","religion:test","faction:test",wealth=500
                )
                state.settlements[uid]=town;rows.append(town)
                if len(rows)>=count:return state,regions,rows
        self.fail("not enough deterministic settlement sites in bounded test window")

    def test_v3_routes_have_exact_portals_infrastructure_and_hinterlands(self):
        world,_,_=self.make_world();state,regions,towns=self.make_state(world)
        planner=RoutePlanner(world,state,regions)
        plans=planner.sync_network(state.settlements.values(),persist=True)
        self.assertTrue(plans)
        self.assertLessEqual(len(plans),(len(towns)-1)+max(1,len(towns)//3))
        for plan in plans:
            self.assertEqual(len(plan.portals),max(0,len(plan.region_path)-1))
            for portal in plan.portals:
                a=tuple(portal["from_cell"]);b=tuple(portal["to_cell"])
                self.assertEqual(abs(a[0]-b[0])+abs(a[1]-b[1]),1)
            self.assertIn(plan.uid,state.route_infrastructure)
        self.assertTrue(any(t.route_centrality>0 for t in towns))
        self.assertTrue(state.factions["faction:test"].hinterland_regions)
        restored=LivingWorldState.from_dict(state.to_dict())
        self.assertEqual(
            state.route_infrastructure[plans[0].uid].condition,
            restored.route_infrastructure[plans[0].uid].condition,
        )

    def test_settlement_gateway_and_local_cells_consume_selected_route(self):
        world,reg,_=self.make_world();state,regions,towns=self.make_state(world)
        planner=RoutePlanner(world,state,regions)
        plans=planner.sync_network(state.settlements.values(),persist=True)
        endpoint=next(t for t in towns if any(t.uid in (p.origin,p.destination) for p in plans))
        skeletons=SettlementSkeletonPlanner(world)
        region=regions.plan(endpoint.region_x,endpoint.region_y,persist=True)
        links=planner.links_for_settlement(endpoint.uid)
        direct=skeletons.plan(
            region,endpoint.uid,endpoint.population,
            culture_id=endpoint.culture_id,faction_id=endpoint.faction_id,
            route_links=links,persist=False,
        )
        self.assertIsNotNone(direct)
        physical=SettlementPhysicalizationSystem(world,reg,regions,skeletons,planner)
        physical.sync(state.settlements.values(),(endpoint.region_x,endpoint.region_y),radius=0)
        skeleton=physical.skeleton_for(endpoint.uid)
        self.assertIsNotNone(skeleton)
        selected={p.uid for p in plans if endpoint.uid in (p.origin,p.destination)}
        self.assertTrue(any(r.route_id in selected for r in skeleton.roads))
        segments=physical.route_segments()
        self.assertTrue(any(r.route_id in selected for r in segments))
        road_cells=[c for c in physical.cells() if any(route_id in c.road_ids for route_id in selected)]
        self.assertTrue(road_cells)

    def test_infrastructure_wear_maintenance_and_economy_share_route_authority(self):
        world,reg,_=self.make_world();state,regions,towns=self.make_state(world)
        planner=RoutePlanner(world,state,regions)
        plans=planner.sync_network(state.settlements.values(),persist=True)
        plan=plans[0];infra=state.route_infrastructure[plan.uid]
        start=infra.condition
        for i in range(8):planner.record_usage(plan.uid,100+i,1)
        self.assertLess(infra.condition,start)
        infra.condition=55
        treasury=state.factions["faction:test"].treasury
        planner.monthly_update(30*1440)
        self.assertGreater(infra.condition,54)
        self.assertLess(state.factions["faction:test"].treasury,treasury)

        economy=EconomySystem(state,reg,world.generator.world_seed,HistorySystem(state))
        economy.attach_route_planner(planner)
        economy._ensure_routes(31*1440)
        self.assertTrue(state.trade_routes)
        self.assertTrue(all(r.physical_route_id for r in state.trade_routes.values()))
        self.assertTrue(all(r.physical_route_id in {p.uid for p in planner.active_plans()} for r in state.trade_routes.values()))


if __name__=="__main__":
    unittest.main()
