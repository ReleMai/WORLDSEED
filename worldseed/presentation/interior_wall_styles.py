"""Visual structural/partition wall classification for existing interior plans.

Never mutate save schema, rooms, wall hitboxes, LOS, inventories or owners.
Four perimeter wall rectangles are generated by interior_templates, and
legacy plans are recognised by the same physical perimeter geometry.
"""
from __future__ import annotations


def wall_kind(rect, width: int, height: int) -> str:
    x,y,x1,y1=rect
    w,h=x1-x,y1-y
    if width <= 0 or height <= 0 or w <= 0 or h <= 0:
        return 'partition'
    # Exterior faces must both TOUCH the plan perimeter and continue along
    # a significant portion of it. Internal door openings remain partitions.
    horizontal=(y<=0 or y1>=height) and w>=max(2*h,width*.4)
    vertical=(x<=0 or x1>=width) and h>=max(2*w,height*.4)
    return 'structural' if horizontal or vertical else 'partition'


def wall_texture(base: str, kind: str) -> str:
    if kind != 'structural':
        return base
    # Distinct heavy shells with no new sprite mapping or generated asset.
    if 'stone' in base or 'slate' in base:
        return 'core:wall_fieldstone'
    if 'timber' in base or 'oak' in base or 'wood' in base:
        return 'core:wall_oak_panel'
    return 'core:wall_limewash'
